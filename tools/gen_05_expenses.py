def make_template():
    wb = Workbook()
    ws = wb.active
    ws.title = "経費精算書"
    head = PatternFill("solid", fgColor="1F3864")
    hf = Font(bold=True, color="FFFFFF")

    ws["A1"] = "経費精算書"
    ws["A1"].font = Font(size=16, bold=True)
    for label, cell, val in [("申請者", "A3", "田中 健"), ("所属", "A4", "営業本部 西日本チーム"),
                             ("対象月", "A5", "2026年8月"), ("提出日", "A6", "")]:
        ws[cell] = label
        ws[cell].font = Font(bold=True)
        ws[f"B{cell[1:]}"] = val

    cols = ["No", "日付", "勘定科目", "支払先", "内容/目的", "参加人数",
            "金額(円)", "税区分", "支払方法", "精算額(円)", "自己負担額(円)", "証憑", "備考"]
    widths = [6, 12, 16, 24, 34, 10, 12, 10, 14, 14, 14, 12, 34]
    for j, (c, w) in enumerate(zip(cols, widths), start=1):
        cell = ws.cell(row=8, column=j, value=c)
        cell.fill, cell.font = head, hf
        cell.alignment = Alignment(horizontal="center", wrap_text=True)
        ws.column_dimensions[cell.column_letter].width = w

    # 記入例（1行だけ。ここを真似して埋めてもらう）
    example = [1, "2026-08-04", "旅費交通費", "JR東海", "東京→新大阪（ミナト製作所訪問）",
               "", 14720, "10%", "現金", 14720, 0, "有", "領収書 receipts/01_shinkansen.txt"]
    for j, v in enumerate(example, start=1):
        c = ws.cell(row=9, column=j, value=v)
        c.font = Font(italic=True, color="808080")
    ws.cell(row=9, column=14, value="← 記入例。実データで置き換えること").font = Font(italic=True, color="C00000")

    ws.cell(row=40, column=6, value="合計").font = Font(bold=True)
    ws.cell(row=40, column=10, value="=SUM(J9:J39)").font = Font(bold=True)

    dv = DataValidation(type="list", formula1='"旅費交通費,宿泊費,交際費,会議費,消耗品費,図書研究費,研修費"', allow_blank=True)
    ws.add_data_validation(dv)
    dv.add(f"C9:C39")
    dv2 = DataValidation(type="list", formula1='"現金,私物カード,法人カード,ICカード"', allow_blank=True)
    ws.add_data_validation(dv2)
    dv2.add("I9:I39")

    ws2 = wb.create_sheet("勘定科目マスタ")
    ws2.append(["勘定科目", "説明", "上限", "証憑要否"])
    for c in ws2[1]:
        c.fill, c.font = head, hf
    for row in [
        ["旅費交通費", "電車/新幹線/タクシー/駐車場/航空券", "", "1,000円超は必要"],
        ["宿泊費", "ホテル代（宿泊税込）", "15,000円/泊", "必要"],
        ["交際費", "社外の方を含む会食・手土産", "10,000円/人", "必要"],
        ["会議費", "社内飲食、1人3,000円以下の社外飲食", "3,000円/人", "必要"],
        ["消耗品費", "10万円未満の事務用品・備品", "", "必要"],
        ["図書研究費", "業務書籍・資料", "", "必要"],
        ["研修費", "セミナー/カンファレンス参加費", "", "必要"],
    ]:
        ws2.append(row)
    for letter, w in zip("ABCD", [16, 40, 16, 20]):
        ws2.column_dimensions[letter].width = w

    ws3 = wb.create_sheet("差戻し履歴")
    ws3.append(["提出日", "差戻し日", "理由"])
    for c in ws3[1]:
        c.fill, c.font = head, hf
    ws3.append(["2026-07-05", "2026-07-08", "会食の参加人数が未記入。1人単価が判定できないため差戻し。"])
