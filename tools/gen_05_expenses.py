def main():
    for name, body in RECEIPTS.items():
        (BASE / "receipts" / name).write_text(body, encoding="utf-8")
    (BASE / "出張メモ_手書き起こし.txt").write_text(MEMO, encoding="utf-8")
    (BASE / "法人カード明細_2026-08.csv").write_text(CARD_CSV, encoding="utf-8")
    (BASE / "経費精算規程.md").write_text(RULES, encoding="utf-8")
    (BASE / "出張報告_田中.md").write_text(REPORT, encoding="utf-8")
    make_template()
    print("wrote", len(RECEIPTS), "receipts +4 docs")


if __name__ == "__main__":
    main()
