def build_rows():
    rows = []
    for i, (comp, person, industry, plan) in enumerate(COMPANIES):
        lic = random.choice([10, 20, 25, 30, 50, 80, 100, 150])
        unit = UNIT_PRICE[plan]
        current = lic * unit // (10 if plan == "エンタープライズ" else 1)
        rate = random.choice([0, 0, 0, 3, 3, 5, 5, 8, 10, 12])
        new = int(round(current * (1 + rate / 100) / 1000) * 1000)
        score = random.randint(28, 96)
        risk = "高" if score < 40 else ("中" if score < 65 else "低")
        month = random.choice([10, 11, 12])
        day = random.choice([15, 20, 25, 28, 31 if month == 12 else 30])
        rows.append([
            comp, person, industry, plan, lic, current, rate, new,
            f"2026-{month:02d}-{day:02d}", score, risk,
            ISSUES[i % len(ISSUES)], REPS[i % len(REPS)],
        ])
    return rows


